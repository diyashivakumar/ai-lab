def is_variable(x):
    return isinstance(x, str) and x.islower() and len(x) == 1

def apply_substitution(term, subs):
    while isinstance(term, str) and term in subs:
        term = subs[term]
    return term

def unify(x, y, subs):
    x = apply_substitution(x, subs)
    y = apply_substitution(y, subs)

    if x == y:
        return subs

    if is_variable(x):
        if x in str(y):
            return None
        subs[x] = y
        return subs

    if is_variable(y):
        if y in str(x):
            return None
        subs[y] = x
        return subs

    if isinstance(x, tuple) and isinstance(y, tuple):
        if x[0] != y[0] or len(x) != len(y):
            return None

        for a, b in zip(x[1:], y[1:]):
            subs = unify(a, b, subs)
            if subs is None:
                return None

        return subs

    return None

def parse_expression(expr_str):
    expr_str = expr_str.strip().replace(" ", "")
    if '(' in expr_str and expr_str.endswith(')'):
        name = expr_str.split('(')[0]
        args_str = expr_str[len(name)+1:-1]
        args = args_str.split(',')
        return tuple([name] + args)
    return expr_str

